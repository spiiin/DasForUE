"""Render Docs/Reference/ReloadMatrix.md from Tests/ReloadMatrix/expected.json.

The automation tests DasForUE.ReloadMatrix.Editor and .PIE apply every declaration change of every entity
kind with the automatic Reimport and compare the outcome with the expected file. This script turns that
file into the reference page; --check fails when the page is stale.

    python Scripts/RenderReloadMatrix.py [--check] [--from-actual]

--from-actual first copies the outcomes of the last run (logs/reload-matrix.json) into the expected file.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXPECTED = ROOT / "Tests" / "ReloadMatrix" / "expected.json"
ACTUAL = ROOT / "logs" / "reload-matrix.json"
PAGE = ROOT / "Docs" / "Reference" / "ReloadMatrix.md"

KINDS = ["actor", "composed", "pawn", "character", "child", "evented", "data_asset", "primary_data_asset", "save_game", "component"]
KIND_TITLES = {
    "actor": "Actor",
    "composed": "Actor with components",
    "pawn": "Pawn",
    "character": "Character",
    "child": "Child of a DSL parent",
    "evented": "Actor with event and delegate",
    "data_asset": "DataAsset",
    "primary_data_asset": "PrimaryDataAsset",
    "save_game": "SaveGame",
    "component": "ActorComponent in an actor Blueprint",
}
TYPES = ["int", "float", "bool", "string", "name", "text", "byte", "vector", "soft", "array", "map", "set"]
FIELD_CHANGES = ["add_field", "remove_field", "rename_field", "retype_field", "change_default", "make_read_only"]
METHOD_CHANGES = ["add_method", "remove_method", "change_signature"]
COMPONENT_CHANGES = ["add_component", "remove_component", "rename_component", "change_component_default",
                     "change_attach"]
EVENT_CHANGES = ["add_event", "remove_event", "add_interface"]
CHILD_CHANGES = ["parent_add_field", "reparent"]
MODES = ["editor", "pie"]
MARK = {"migrated": "✅", "lossy": "⚠️", "refused": "⛔", "broken": "❌"}


def mark(cells, key):
    row = cells.get(key)
    return MARK.get(row["outcome"], "?") if row else "·"


def render(data):
    out = [
        "# Reload matrix",
        "",
        "<!-- Generated by Scripts/RenderReloadMatrix.py from Tests/ReloadMatrix/expected.json; do not edit. -->",
        "",
        "What the automatic reimport (save of a `.das` file, `Das.DSL.Reimport`) does with each declaration",
        "change, checked by `DasForUE.ReloadMatrix.Editor` and `.PIE` (suite `reload-matrix`). Every cell starts",
        "from an imported Blueprint with a placed instance that overrides the changed field and another field,",
        "applies one change and checks the class, the instance values and the editor instance without overrides.",
        "",
        "| Mark | Outcome |",
        "| --- | --- |",
        "| ✅ | migrated: applied, instance values kept |",
        "| ⚠️ | lossy: applied, but an instance value was lost |",
        "| ⛔ | refused: nothing changed; the notification names the reason |",
        "| ❌ | broken: an invariant failed (a bug) |",
        "",
        "The plan for turning refusals into migrations: [Structural changes](../Dev/Plans/StructuralChanges.md).",
        "",
    ]
    for mode in MODES:
        cells = data.get(mode, {})
        out += [f"## {'Editor' if mode == 'editor' else 'During PIE'}", ""]
        out += ["### Fields of an Actor, by type", ""]
        out.append("| Change | " + " | ".join(TYPES) + " |")
        out.append("| --- |" + " --- |" * len(TYPES))
        for change in FIELD_CHANGES:
            out.append(f"| {change} | " + " | ".join(mark(cells, f"actor/{t}/{change}") for t in TYPES) + " |")
        out += ["", "### By class kind (int field)", ""]
        out.append("| Change | " + " | ".join(KIND_TITLES[k] for k in KINDS) + " |")
        out.append("| --- |" + " --- |" * len(KINDS))
        for change in FIELD_CHANGES + METHOD_CHANGES + COMPONENT_CHANGES + EVENT_CHANGES + CHILD_CHANGES:
            out.append(f"| {change} | " + " | ".join(mark(cells, f"{k}/int/{change}") for k in KINDS) + " |")
        reasons = sorted(
            (key, row["message"]) for key, row in cells.items() if row["outcome"] != "migrated" and row["message"]
        )
        if reasons:
            out += ["", "<details><summary>Reasons</summary>", ""]
            out += [f"- `{key}`: {message}" for key, message in reasons]
            out += ["", "</details>"]
        out.append("")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--from-actual", action="store_true")
    args = parser.parse_args()
    if args.from_actual:
        EXPECTED.parent.mkdir(parents=True, exist_ok=True)
        actual = json.loads(ACTUAL.read_text(encoding="utf-8"))
        EXPECTED.write_text(json.dumps(actual, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
                            encoding="utf-8", newline="\n")
    page = render(json.loads(EXPECTED.read_text(encoding="utf-8")))
    if args.check:
        if not PAGE.exists() or PAGE.read_text(encoding="utf-8") != page:
            print("DAS_RELOAD_MATRIX_DOC=STALE run: python Scripts/RenderReloadMatrix.py")
            return 1
        print("DAS_RELOAD_MATRIX_DOC=PASS")
        return 0
    PAGE.write_text(page, encoding="utf-8", newline="\n")
    print(f"DAS_RELOAD_MATRIX_DOC=WRITTEN {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
