"""Generate the cooked allowlist and nominal dependency views from UE reflection."""
import argparse,hashlib,json,re
from DiscoverNativeGameplay import declarations
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
def generate(ir,script_dirs=None):
 if ir.get('schema_version')!=5:raise ValueError('Unsupported native gameplay manifest')
 classes=ir['classes'];seen=set();refs=set()
 header=['// Generated by Scripts/GenerateNativeGameplay.py. Do not edit.','#pragma once',
 'struct FDasNativeGameplayField { const TCHAR *Class,*Name,*Kind,*TypePath,*Signature,*Declaring; bool ReadOnly; };',
 'struct FDasNativeGameplayMethod { const TCHAR *Class,*Name,*Signature; };',
 'struct FDasNativeGameplayDefault { const TCHAR *Class,*Method,*Name,*Text; };',
 'inline const FDasNativeGameplayField DasNativeGameplayFields[] = {']
 def q(s):return 'TEXT('+json.dumps(s,ensure_ascii=True)+')'
 methods=[];defaults=[];used=[];soft_types={}
 def visit(value,depth=0):
  if depth>16:raise ValueError('Recursive native type')
  if value['kind'] not in ('int','float','double','bool','string','name','object','class','struct','enum','byte','text','array','map','set'):raise ValueError('Unsupported type')
  used.append(value)
  soft=value.get('soft_reference')
  if soft is not None:
   base=soft.get('base');cls=soft.get('class_ref')
   if value['kind']!='struct' or not isinstance(base,str) or not re.fullmatch(r'/Script/[A-Za-z_][A-Za-z0-9_]*\.[A-Za-z_][A-Za-z0-9_]*',base) or type(cls)!=bool:raise ValueError('Invalid native soft reference')
   expected='/Script/DasRuntime.DasSoft'+('Class_' if cls else 'Object_')+hashlib.md5(base.encode()).hexdigest()
   if value['type_path']!=expected:raise ValueError('Noncanonical native soft carrier')
   if expected in soft_types and soft_types[expected]!=soft:raise ValueError('Conflicting native soft descriptor')
   soft_types[expected]=soft;refs.add(base)
  elif value['kind']=='struct' and value['type_path'].startswith(('/Script/DasRuntime.DasSoftObject_','/Script/DasRuntime.DasSoftClass_')):raise ValueError('Missing native soft descriptor')
  if value['kind']=='object':refs.add(value['type_path'])
  if value['kind']=='array':
   if value.get('type_path') or 'element' not in value or value['element']['kind'] in ('array','map','set','byte','text','class'):raise ValueError('Unsupported native array element')
   visit(value['element'],depth+1)
  if value['kind'] in ('map','set'):
   key=value.get('key' if value['kind']=='map' else 'element')
   if value.get('type_path') or not key or key['kind'] not in ('int','string','name','enum','object'):raise ValueError('Unsupported native hash key')
   visit(key,depth+1)
   if value['kind']=='map':
    item=value.get('value')
    if not item or item['kind'] in ('array','map','set','byte','text','class'):raise ValueError('Unsupported native map value')
    visit(item,depth+1)
 for struct in ir['structs']:
  for field in struct['fields']:visit(field)

 for cls in classes:
  path=cls['path']
  if path in seen or not path.startswith('/Script/'):raise ValueError('Invalid native class')
  seen.add(path);refs.add(path)
  for domain in ['fields','methods']:
   names=set()
   for item in cls[domain]:
    name=item['name']
    if name in names or not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*',name):raise ValueError('Invalid member name')
    names.add(name)
    values=[item] if domain=='fields' else item['parameters']
    for value in values:
     visit(value)
    if domain=='fields':header.append(' {'+','.join([q(path),q(name),q(item['kind']),q(item['type_path']),q(item['signature']),q(item['declaring_class']),'true' if item['readonly'] else 'false'])+'},')
    else:
     methods.append(' {'+','.join([q(path),q(name),q(item['signature'])])+'},')
     for p in item['parameters']:
      if 'default_text' in p:defaults.append(' {'+','.join(map(q,[path,name,p['name'],p['default_text']]))+'},')
 header+=['};','inline const FDasNativeGameplayMethod DasNativeGameplayMethods[] = {',*methods,'};','inline const FDasNativeGameplayDefault DasNativeGameplayDefaults[] = {',*defaults,'};']
 # Reuse the canonical imported wrappers. Never introduce two nominal types for
 # the same native class just because another API returns it.
 scripts=ROOT/'Plugins/DasForUE/Content/Das/Scripts';directories=[scripts,*[Path(p) for p in (script_dirs or [])]];known={};known_enums={};visited=set()
 def imports(module):
  if module in visited:return
  visited.add(module)
  matches=list(dict.fromkeys(d.resolve()/(module+'.das') for d in directories if (d/(module+'.das')).is_file()))
  if len(matches)>1:raise ValueError('Ambiguous native module '+module)
  if not matches:return
  file=matches[0]
  source=file.read_text(encoding='utf-8-sig')
  _,dependencies,objects,enums=declarations(source)
  if 'ue_native_gameplay' in dependencies:raise ValueError('Canonical native module depends on generated bindings: '+module)
  for dependency in dependencies:imports(dependency)
  for path,name in objects:
   if path in known and known[path]!=(module,name):raise ValueError('Ambiguous imported native view '+path)
   known[path]=(module,name)
  for path,name in enums:
   if path in known_enums and known_enums[path]!=(module,name):raise ValueError('Ambiguous imported native enum '+path)
   known_enums[path]=(module,name)
 discovery=ir.get('discovery')
 if not discovery or discovery.get('schema_version')!=1:raise ValueError('Missing native discovery metadata')
 modules=discovery['modules']
 if modules!=sorted(set(modules)) or any(not re.fullmatch(r'[A-Za-z_]\w*',m) or m=='ue_native_gameplay' for m in modules):raise ValueError('Invalid discovery modules')
 for module in modules:imports(module)
 for item in discovery['classes']:
  if known.get(item['path'])!=(item['module'],item['name']):raise ValueError('Stale native declaration '+item['path'])
 if seen!={item['path'] for item in discovery['classes']}:raise ValueError('Native receiver/discovery mismatch')
 header += ['struct FDasNativeGameplayView { const TCHAR *Class,*Source; };','inline const FDasNativeGameplayView DasNativeGameplayViews[] = {']
 source=['options gen2','module ue_native_gameplay public',*['require '+m+' public' for m in sorted(set(modules)|{'ue_soft_references'})],'','// Generated dependency views; methods/fields are synthesized from the compiled manifest.']
 view_names={}
 for path in sorted(refs):
  if path in known:
   module,name=known[path]
   view_names[path]=name
   header.append(' {'+q(path)+','+q(module+'::'+name)+'},')
   continue
  if not path.startswith('/Script/'):raise ValueError('Non-native dependency')
  name='Native_'+path.rsplit('.',1)[-1]+'Ref_'+hashlib.sha256(path.encode()).hexdigest()[:8]
  view_names[path]=name
  header.append(' {'+q(path)+','+q('ue_native_gameplay::'+name)+'},')
  source += [f'[ue_native_object(path="{path}")]',f'struct {name} {{ handle:UObjectHandle }}',f'def {name}_from(value:UObjectHandle):{name} {{ return {name}(handle=ue_cast_nullable_object(value,"{path}")) }}','']
 header.append('};')
 soft_names={}
 header += ['struct FDasNativeGameplaySoftType { const TCHAR *Path,*Source; };','inline const FDasNativeGameplaySoftType DasNativeGameplaySoftTypes[] = {']
 for path,soft in sorted(soft_types.items()):
  name='NativeSoft'+('Class_' if soft['class_ref'] else 'Object_')+soft['base'].rsplit('.',1)[-1]+'_'+hashlib.sha256(path.encode()).hexdigest()[:8]
  soft_names[path]=name
  source += [f"typedef {name} = $UESoft{'Class' if soft['class_ref'] else 'Object'}<{view_names[soft['base']]}>\n"]
  header.append(' {'+q(path)+','+q('ue_native_gameplay::'+name)+'},')
 header.append('};')
 header += ['struct FDasNativeGameplayEnum { const TCHAR *Path,*Source; };','inline const FDasNativeGameplayEnum DasNativeGameplayEnums[] = {']
 enums={};enum_names=set()
 for enum in ir['enums']:
  path=enum['path'];name=path.rsplit('.',1)[-1]
  if path in enums or not path.startswith('/Script/') or not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*',name) or name in enum_names:raise ValueError('Invalid or duplicate native enum')
  enums[path]=enum;enum_names.add(name);numbers=set();names=set()
  if not enum['entries']:raise ValueError('Empty native enum')
  for entry in enum['entries']:
   member,value=entry['name'],entry['value']
   if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*',member) or member in names or member.endswith('_MAX') or type(value)!=int or not 0<=value<=254 or value in numbers:raise ValueError('Invalid native enum entry')
   names.add(member);numbers.add(value)
  if path in known_enums:module,view=known_enums[path]
  else:
   module,view='ue_native_gameplay',name
   source += [f'[ue_native_enum(path="{path}")]',f'enum {view} {{',*[f"    {e['name']}={e['value']}" for e in enum['entries']],'}','']
  header.append(' {'+q(path)+','+q(module+'::'+view)+'},')
 for value in used:
  if value['kind']=='enum' and value['type_path'] not in enums:raise ValueError('Missing native enum definition')
 header.append('};')
 math={'/Script/CoreUObject.Vector':'UEVector','/Script/CoreUObject.Vector2D':'UEVector2D','/Script/CoreUObject.Rotator':'UERotator','/Script/CoreUObject.Transform':'UETransform'}
 structs={};names=set(enum_names)|set(view_names.values())
 for item in ir['structs']:
  path=item['path'];name=path.rsplit('.',1)[-1]
  if path in structs or not path.startswith('/Script/') or not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*',name) or name in names or not item['fields']:raise ValueError('Invalid native struct')
  fields=[f['name'] for f in item['fields']]
  if len(set(fields))!=len(fields) or any(not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*',f) for f in fields):raise ValueError('Invalid struct field')
  structs[path]=item;names.add(name)
 def typename(t):
  k=t['kind'];path=t['type_path']
  if path in soft_names:return soft_names[path]
  if k=='set':return 'table<'+keyname(t['element'])+'>'
  if k=='map':return 'table<'+keyname(t['key'])+';'+typename(t['value'])+'>'
  if k=='array':return 'array<'+typename(t['element'])+'>'
  if k=='object':return view_names[path]
  if k=='enum':return known_enums[path][1] if path in known_enums else path.rsplit('.',1)[-1]
  if k=='struct':
   if path not in math and path not in structs:raise ValueError('Missing native struct definition')
   return math.get(path,path.rsplit('.',1)[-1])
  return {'name':'UENameValue','class':'UEClassHandle','byte':'int','text':'UETextValue'}.get(k,k)
 def keyname(t):return '$UEObjectKey<'+typename(t)+'>' if t['kind']=='object' else typename(t)
 header += ['struct FDasNativeGameplayStruct { const TCHAR *Path,*Source,*Signature; };','inline const FDasNativeGameplayStruct DasNativeGameplayStructs[] = {']
 active=set();done=set()
 def emit(path):
  if path in done or path in math:return
  if path in active:raise ValueError('Recursive native struct')
  if path not in structs:raise ValueError('Missing native struct definition')
  active.add(path);item=structs[path];name=path.rsplit('.',1)[-1]
  def dependencies(field):
   if field['kind'] in ('array','set'):dependencies(field['element'])
   elif field['kind']=='map':dependencies(field['key']);dependencies(field['value'])
   elif field['kind']=='struct' and field['type_path'] not in soft_names:emit(field['type_path'])
  for field in item['fields']:dependencies(field)
  source.extend([f'[ue_native_struct(path="{path}")]',f'struct {name} {{',*[f"    {f['name']}:{typename(f)}" for f in item['fields']],'}',''])
  header.append(' {'+q(path)+','+q('ue_native_gameplay::'+name)+','+q(item['signature'])+'},')
  active.remove(path);done.add(path)
 for path in sorted(structs):emit(path)
 for value in used:
  if value['kind']=='struct':typename(value)
 header.append('};')
 # A small project can have no soft types/defaults/etc. C++ forbids T[0].
 header_text='\n'.join(header)+'\n'
 header_text,empty=re.subn(r'inline const (\w+) (\w+)\[\] = \{\n\};',r'inline const std::array<\1, 0> \2{};',header_text)
 if empty:header_text=header_text.replace('#pragma once\n','#pragma once\n#include <array>\n',1)
 return header_text,'\n'.join(source).rstrip()+'\n'
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('ir',type=Path);p.add_argument('header',type=Path);p.add_argument('module',type=Path);p.add_argument('--check',action='store_true');p.add_argument('--scripts',type=Path,action='append',default=[]);a=p.parse_args()
 results=generate(json.loads(a.ir.read_text(encoding='utf-8-sig')),a.scripts)
 for file,source in zip([a.header,a.module],results):
  if a.check:
   if not file.exists() or file.read_text(encoding='utf-8')!=source:raise SystemExit('Stale generated file: '+str(file))
  else:file.write_text(source,encoding='utf-8')
 print('DAS_NATIVE_GAMEPLAY_GENERATE=PASS')
