"""Generate the cooked allowlist and nominal dependency views from UE reflection."""
import argparse,hashlib,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
def generate(ir):
 if ir.get('schema_version')!=2:raise ValueError('Unsupported native gameplay manifest')
 classes=ir['classes'];seen=set();refs=set()
 header=['// Generated by Scripts/GenerateNativeGameplay.py. Do not edit.','#pragma once',
 'struct FDasNativeGameplayField { const TCHAR *Class,*Name,*Kind,*TypePath,*Signature,*Declaring; bool ReadOnly; };',
 'struct FDasNativeGameplayMethod { const TCHAR *Class,*Name,*Signature; };',
 'struct FDasNativeGameplayDefault { const TCHAR *Class,*Method,*Name,*Text; };',
 'inline const FDasNativeGameplayField DasNativeGameplayFields[] = {']
 def q(s):return 'TEXT('+json.dumps(s,ensure_ascii=True)+')'
 methods=[];defaults=[]
 for cls in classes:
  path=cls['path']
  if path in seen or not path.startswith('/Script/'):raise ValueError('Invalid native class')
  seen.add(path);refs.add(path)
  for domain in ['fields','methods']:
   names=set()
   for item in cls[domain]:
    name=item['name']
    if name in names or not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*',name):raise ValueError('Invalid member name')
    names.add(name)
    values=[item] if domain=='fields' else item['parameters']
    for value in values:
     if value['kind'] not in ('int','float','double','bool','string','name','object','class','struct','enum'):raise ValueError('Unsupported type')
     if value['kind']=='object':refs.add(value['type_path'])
    if domain=='fields':header.append(' {'+','.join([q(path),q(name),q(item['kind']),q(item['type_path']),q(item['signature']),q(item['declaring_class']),'true' if item['readonly'] else 'false'])+'},')
    else:
     methods.append(' {'+','.join([q(path),q(name),q(item['signature'])])+'},')
     for p in item['parameters']:
      if 'default_text' in p:defaults.append(' {'+','.join(map(q,[path,name,p['name'],p['default_text']]))+'},')
 header+=['};','inline const FDasNativeGameplayMethod DasNativeGameplayMethods[] = {',*methods,'};','inline const FDasNativeGameplayDefault DasNativeGameplayDefaults[] = {',*defaults,'};']
 # Reuse the canonical imported wrappers. Never introduce two nominal types for
 # the same native class just because another API returns it.
 scripts=ROOT/'Plugins/DasForUE/Content/Das/Scripts';known={};known_enums={};visited=set()
 def imports(module):
  if module in visited:return
  visited.add(module);file=scripts/(module+'.das')
  if not file.exists():return
  source=file.read_text(encoding='utf-8-sig')
  for dependency in re.findall(r'^require\s+(\w+)',source,re.M):imports(dependency)
  for path,name in re.findall(r'\[ue_native_object\(path\s*=\s*"([^"]+)"\)\]\s*struct\s+(\w+)',source):
   if path in known and known[path]!=(module,name):raise ValueError('Ambiguous imported native view '+path)
   known[path]=(module,name)
  for path,name in re.findall(r'\[ue_native_enum\(path\s*=\s*"([^"]+)"\)\]\s*enum\s+(\w+)',source):
   if path in known_enums and known_enums[path]!=(module,name):raise ValueError('Ambiguous imported native enum '+path)
   known_enums[path]=(module,name)
 imports('ue_character_control')
 header += ['struct FDasNativeGameplayView { const TCHAR *Class,*Source; };','inline const FDasNativeGameplayView DasNativeGameplayViews[] = {']
 source=['options gen2','module ue_native_gameplay public','require ue_character_control public','','// Generated dependency views; methods/fields are synthesized from the compiled manifest.']
 for path in sorted(refs):
  if path in known:
   module,name=known[path]
   header.append(' {'+q(path)+','+q(module+'::'+name)+'},')
   continue
  if not path.startswith('/Script/'):raise ValueError('Non-native dependency')
  name='Native_'+path.rsplit('.',1)[-1]+'Ref_'+hashlib.sha256(path.encode()).hexdigest()[:8]
  header.append(' {'+q(path)+','+q('ue_native_gameplay::'+name)+'},')
  source += [f'[ue_native_object(path="{path}")]',f'struct {name} {{ handle:UObjectHandle }}',f'def {name}_from(value:UObjectHandle):{name} {{ return {name}(handle=ue_cast_nullable_object(value,"{path}")) }}','']
 header.append('};')
 header += ['struct FDasNativeGameplayEnum { const TCHAR *Path,*Source; };','inline const FDasNativeGameplayEnum DasNativeGameplayEnums[] = {']
 enums={};enum_names=set()
 for enum in ir['enums']:
  path=enum['path'];name=path.rsplit('.',1)[-1]
  if path in enums or not path.startswith('/Script/') or not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*',name) or name in enum_names:raise ValueError('Invalid or duplicate native enum')
  enums[path]=enum;enum_names.add(name);numbers=set();names=set()
  if not enum['entries']:raise ValueError('Empty native enum')
  for entry in enum['entries']:
   member,value=entry['name'],entry['value']
   if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*',member) or member in names or member.endswith('_MAX') or type(value)!=int or not 0<=value<=254 or value in numbers:raise ValueError('Invalid native enum entry')
   names.add(member);numbers.add(value)
  if path in known_enums:module,view=known_enums[path]
  else:
   module,view='ue_native_gameplay',name
   source += [f'[ue_native_enum(path="{path}")]',f'enum {view} {{',*[f"    {e['name']}={e['value']}" for e in enum['entries']],'}','']
  header.append(' {'+q(path)+','+q(module+'::'+view)+'},')
 for cls in classes:
  for value in cls['fields']+[p for m in cls['methods'] for p in m['parameters']]:
   if value['kind']=='enum' and value['type_path'] not in enums:raise ValueError('Missing native enum definition')
 header.append('};')
 return '\n'.join(header)+'\n','\n'.join(source).rstrip()+'\n'
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('ir',type=Path);p.add_argument('header',type=Path);p.add_argument('module',type=Path);p.add_argument('--check',action='store_true');a=p.parse_args()
 results=generate(json.loads(a.ir.read_text(encoding='utf-8-sig')))
 for file,source in zip([a.header,a.module],results):
  if a.check:
   if not file.exists() or file.read_text(encoding='utf-8')!=source:raise SystemExit('Stale generated file: '+str(file))
  else:file.write_text(source,encoding='utf-8')
 print('DAS_NATIVE_GAMEPLAY_GENERATE=PASS')
