"""Reference of the plugin's native modules (ue_engine, ue_math, ue_time) from the native binds manifest.

Reads logs/native-binds-manifest.json (written by the DasNativeBindsManifest commandlet) and writes
Docs/Reference/NativeModules.md: the script types, their methods and the free functions of each module, with
their flags and the UFUNCTION a method reflects. Deterministic; --check fails when the checked-in file differs.

    python Scripts/NativeModulesReference.py [--manifest logs/native-binds-manifest.json] [--check]
"""
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PLUGIN_MODULES = ('ue_engine', 'ue_math', 'ue_time')
DEFAULT_MANIFEST = os.path.join(ROOT, 'logs', 'native-binds-manifest.json')
DEFAULT_OUTPUT = os.path.join(ROOT, 'Docs', 'Reference', 'NativeModules.md')


def signature(f, method):
    arguments = f['arguments'][1:] if method else f['arguments']
    text = f['name'] + '(' + ', '.join(arguments) + ')'
    return text + (' : ' + f['result'] if f['result'] != 'void' else '')


def notes(f):
    out = []
    if f['pure']:
        out.append('pure')
    if f['non_null_args']:
        out.append('non-null arguments')
    if f.get('reflects'):
        ufunction = f['reflects'].rsplit(':', 1)[-1]
        out.append('reflects `%s`' % ufunction + ('' if f.get('routed') else ' (kept: %s)' % f.get('route_note', '')))
    return ', '.join(out)


def render(manifest):
    modules = [m for m in manifest['modules'] if m['name'] in PLUGIN_MODULES]
    out = ['# Native modules reference', '',
           'Generated by `Scripts/NativeModulesReference.py` from the native binds manifest (the',
           '`DasNativeBindsManifest` commandlet). The native binds of the plugin: `require <module>` in a script, then',
           'call functions directly and methods with member syntax (`actor.get_actor_location()`). How binds work and',
           'how to write your own: [Native C++ binds](../Guide/Native/NativeBinds.md).', '',
           'Parameters are listed by type; methods omit the receiver. "pure": the compiler may fold a call with constant',
           'arguments. "non-null arguments": a null or expired object argument is a script error. "reflects": gameplay',
           'scripts that call that UFUNCTION on a native reference call this bind instead of reflection.', '']
    for module in modules:
        functions = [f for f in module['functions'] if f['origin'] == 'declared']
        out += ['## ' + module['name'], '']
        types = module['classes']
        if types:
            out += ['Script types: ' + ', '.join('`%s`' % t for t in types) + '. Each type also has `as_<Type>(x)` '
                    '(from `UObjectHandle`, an ancestor or a descendant type; null when the object is not one), '
                    '`x.valid()`, `x.handle()`, `==` and `!=`; a type has the methods of its ancestor types.', '']
        for receiver in types:
            methods = sorted((f for f in functions if f['receiver'] == receiver), key=lambda f: f['name'])
            if not methods:
                continue
            out += ['### ' + receiver, '', '| Method | Notes |', '| --- | --- |']
            out += ['| `%s` | %s |' % (signature(f, True), notes(f)) for f in methods]
            out.append('')
        extensions = sorted((f for f in functions if f['receiver'] and f['receiver'] not in types),
                            key=lambda f: (f['receiver'], f['name']))
        if extensions:
            out += ['### Methods on types of other modules', '', '| Type | Method | Notes |', '| --- | --- | --- |']
            out += ['| `%s` | `%s` | %s |' % (f['receiver'], signature(f, True), notes(f)) for f in extensions]
            out.append('')
        free = sorted((f for f in functions if not f['receiver']), key=lambda f: (f['name'], f['arguments']))
        if free:
            out += ['### Functions', '', '| Function | Notes |', '| --- | --- |']
            out += ['| `%s` | %s |' % (signature(f, False).replace('|', '\\|'), notes(f)) for f in free]
            out.append('')
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--manifest', default=DEFAULT_MANIFEST)
    parser.add_argument('--output', default=DEFAULT_OUTPUT)
    parser.add_argument('--check', action='store_true', help='Fail if the checked-in reference differs')
    args = parser.parse_args()
    text = render(json.load(open(args.manifest, encoding='utf-8')))
    if args.check:
        current = open(args.output, encoding='utf-8').read() if os.path.exists(args.output) else ''
        if current != text:
            sys.exit('Native modules reference is stale: run Scripts/NativeModulesReference.py')
        print('NATIVE_MODULES_REFERENCE=CURRENT')
        return
    with open(args.output, 'w', encoding='utf-8', newline='\n') as w:
        w.write(text)
    print('NATIVE_MODULES_REFERENCE=PASS output=%s' % args.output)


if __name__ == '__main__':
    main()
