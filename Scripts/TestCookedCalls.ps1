param([string]$Engine='C:\src\unreal\UnrealEngine')
$ErrorActionPreference='Stop'
$Repo=Split-Path -Parent $PSScriptRoot
$Project=Join-Path $Repo 'Tests\DasForUESmoke\DasForUESmoke.uproject'
$Logs=Join-Path $Repo 'logs'
& (Join-Path $Engine 'Engine\Build\BatchFiles\Build.bat') DasForUESmokeEditor Win64 Development "-Project=$Project" -WaitMutex -NoXGE -MaxParallelActions=12
if($LASTEXITCODE){throw 'Cooked calls editor build failed'}
$Stage=Join-Path $Repo 'Build\FunctionLibraries'
New-Item -ItemType Directory -Path $Stage -Force | Out-Null
$IR=Join-Path $Stage 'Api.json'
& (Join-Path $Engine 'Engine\Binaries\Win64\UnrealEditor-Cmd.exe') $Project -run=DasExport "-Selection=$Repo\Bindings\FunctionLibraries.json" "-Output=$IR" -unattended -NullRHI -nosplash "-abslog=$Logs\cooked-calls-bindings-export.log"
if($LASTEXITCODE){throw 'Library export failed'}
& 'C:\Python312\python.exe' (Join-Path $Repo 'Scripts\GenerateBindings.py') $IR (Join-Path $Repo 'Plugins\DasForUE\Content\Das\Scripts\ue_library_generated.das') --module ue_library_generated
if($LASTEXITCODE){throw 'Library generation failed'}
$ProbeId=[Guid]::NewGuid().ToString('N')
$Map="/Game/DasCookedCalls/$ProbeId/Map"
$ExportLog=Join-Path $Logs 'cooked-calls-export.log'
& (Join-Path $Engine 'Engine\Binaries\Win64\UnrealEditor-Cmd.exe') $Project -run=DasCookedCalls "-ProbeId=$ProbeId" -unattended -NullRHI -nosplash -stdout "-abslog=$ExportLog"
if($LASTEXITCODE -or !(Select-String -LiteralPath $ExportLog -SimpleMatch 'DAS_COOKED_CALLS_EXPORT=PASS')){throw 'Cooked calls export failed'}
$ReopenLog=Join-Path $Logs 'class-methods-reopen.log'
& (Join-Path $Engine 'Engine\Binaries\Win64\UnrealEditor-Cmd.exe') $Project -run=DasCookedCalls "-ProbeId=$ProbeId" -Phase=Reopen -unattended -NullRHI -nosplash "-abslog=$ReopenLog"
if($LASTEXITCODE -or !(Select-String -LiteralPath $ReopenLog -SimpleMatch 'DAS_CLASS_METHODS_REOPEN=PASS')){throw 'Class methods fresh-process reopen failed'}
& (Join-Path $PSScriptRoot 'TestPackaged.ps1') -Engine $Engine -AdditionalMaps $Map -SkipZenStore
$Exe=Join-Path $Repo 'Build\Packaged\Windows\DasForUESmoke\Binaries\Win64\DasForUESmoke.exe'
$Log=Join-Path $Logs 'cooked-calls-runtime.log'
$Process=Start-Process -FilePath $Exe -ArgumentList $Map,'-DasCookedCalls','-nullrhi','-unattended','-nosplash',"-abslog=$Log" -WindowStyle Hidden -PassThru -Wait
if($Process.ExitCode -or !(Select-String -LiteralPath $Log -SimpleMatch 'DAS_COOKED_CALLS_RESULT=PASS')){throw "Cooked calls failed ($($Process.ExitCode))"}
# Cleanup only the unique source assets generated by this run; keep the packaged archive.
$ExpectedParent=[IO.Path]::GetFullPath((Join-Path $Repo 'Tests\DasForUESmoke\Content\DasCookedCalls'))
if($ProbeId -notmatch '^[0-9a-fA-F]{32}$'){throw 'Invalid cleanup GUID'}
$SourceDirectory=[IO.Path]::GetFullPath((Join-Path $ExpectedParent $ProbeId))
if([IO.Path]::GetDirectoryName($SourceDirectory) -ne $ExpectedParent){throw 'Unexpected cleanup directory'}
if(Test-Path -LiteralPath $SourceDirectory){
    if((Get-Item -LiteralPath $SourceDirectory).Attributes -band [IO.FileAttributes]::ReparsePoint){throw 'Refuse test cleanup through reparse point'}
    Remove-Item -LiteralPath $SourceDirectory -Recurse -Force
}
Write-Output "DAS_COOKED_CALLS_PROBE=PASS map=$Map"
