int32 PinNumberKind(const FEdGraphPinType& T)
{
    if (T.ContainerType != EPinContainerType::None)
        return -1;
    if (T.PinCategory == UEdGraphSchema_K2::PC_Int)
        return 0;
    if (T.PinCategory == UEdGraphSchema_K2::PC_Real)
        return T.PinSubCategory == UEdGraphSchema_K2::PC_Float    ? 1
               : T.PinSubCategory == UEdGraphSchema_K2::PC_Double ? 6
                                                                  : -1;
    return -1;
}
FName CastName(int32 A, int32 B)
{
    return A == 0 ? (B == 1 ? TEXT("IntToFloat"): TEXT("IntToDouble"))
                  : A == 1
        ? (B == 0 ? TEXT("FloatToInt"): TEXT("FloatToDouble"))
        : (B == 0 ? TEXT("DoubleToInt"): TEXT("DoubleToFloat"));
}
