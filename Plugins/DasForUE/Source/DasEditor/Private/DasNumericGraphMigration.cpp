struct FDasNumericGraphMigration::FImpl
{
    struct FPin
    {
        TStrongObjectPtr<UEdGraphNode> Node;
        FName Name;
        EEdGraphPinDirection Direction;
        FGuid Guid;
        FEdGraphPinType Type;
        FString Default, AutoDefault;
        FText Text;
        TWeakObjectPtr<UObject> Object;
        bool Orphaned = false;
    };
    struct FGraph
    {
        TStrongObjectPtr<UEdGraph> Graph;
        TArray<TStrongObjectPtr<UEdGraphNode>> Nodes;
    };
    struct FEdge
    {
        int32 A, B;
    };
    TArray<FPin> Pins;
    TArray<FGraph> Graphs;
    TArray<FEdge> Edges;
    TMap<int32, FEdGraphPinType> Changes;
    TMap<int32, FString> Defaults, AutoDefaults;
    EDasIntegerRule IntegerRule;
    EDasFloatRule FloatRule;
    FDelegateHandle Handle;
    UEdGraphPin* Pin(int32 N) const
    {
        const auto& P = Pins[N];
        for (auto* Current : P.Node->Pins)
            if (Current && ((P.Guid.IsValid() && Current->PersistentGuid == P.Guid) ||
                            (Current->PinName == P.Name && Current->Direction == P.Direction)))
                return Current;
        return nullptr;
    }
    FEdGraphPinType Type(int32 N) const
    {
        const auto* T = Changes.Find(N);
        return T ? *T : Pins[N].Type;
    }
    ~FImpl()
    {
        if (Handle.IsValid())
            FCoreUObjectDelegates::OnObjectsReplaced.Remove(Handle);
    }
};
FDasNumericGraphMigration::FDasNumericGraphMigration() : Impl(MakeUnique<FImpl>()) {}
FDasNumericGraphMigration::~FDasNumericGraphMigration() = default;
bool FDasNumericGraphMigration::Prepare(const TArray<UBlueprint*>& BPs, UClass* Root,
                                        const TMap<FName, FEdGraphPinType>& Types, EDasIntegerRule I, EDasFloatRule F,
                                        FString& Error, const TMap<UEdGraphPin*, FEdGraphPinType>& ExplicitPins)
{
    auto& S = *Impl;
    S.IntegerRule = I;
    S.FloatRule = F;
    TMap<UEdGraphPin*, int32> Indices;
    for (auto* BP : BPs)
    {
        TArray<UEdGraph*> Graphs;
        BP->GetAllGraphs(Graphs);
        for (auto* Graph : Graphs)
        {
            FImpl::FGraph Image;
            Image.Graph.Reset(Graph);
            for (auto& Entry : Graph->Nodes)
            {
                auto* Node = Entry.Get();
                if (!Node)
                    continue;
                Image.Nodes.Emplace(Node);
                for (auto* Pin : Node->Pins)
                    if (Pin)
                    {
                        FImpl::FPin P;
                        P.Node.Reset(Node);
                        P.Name = Pin->PinName;
                        P.Direction = Pin->Direction;
                        P.Guid = Pin->PersistentGuid;
                        P.Type = Pin->PinType;
                        P.Default = Pin->DefaultValue;
                        P.AutoDefault = Pin->AutogeneratedDefaultValue;
                        P.Text = Pin->DefaultTextValue;
                        P.Object = Pin->DefaultObject;
                        P.Orphaned = Pin->bOrphanedPin;
                        Indices.Add(Pin, S.Pins.Add(MoveTemp(P)));
                    }
            }
            S.Graphs.Add(MoveTemp(Image));
        }
    }
    for (const auto& Pair : Indices)
    {
        const auto* Target = ExplicitPins.Find(Pair.Key);
        if (!Target)
        {
            auto* Node = Cast<UK2Node_Variable>(Pair.Key->GetOwningNode());
            if (!Node)
                continue;
            Target = Types.Find(Node->VariableReference.GetMemberName());
            if (!Target)
                continue;
            auto* P = Node->GetPropertyForVariable();
            if (!P || (!P->GetOwnerClass()->IsChildOf(Root) &&
                       P->GetOwnerClass()->ClassGeneratedBy != Root->ClassGeneratedBy))
                continue;
            if (!Node->IsA<UK2Node_VariableGet>() && !Node->IsA<UK2Node_VariableSet>())
            {
                Error = TEXT("Unsupported Blueprint variable node for numeric migration");
                return false;
            }
            const bool Value = Pair.Key->PinName == Node->VariableReference.GetMemberName() ||
                               (Node->IsA<UK2Node_VariableSet>() && Pair.Key->PinName == FName(TEXT("Output_Get")));
            if (!Value)
                continue;
        }
        if (Pair.Key->bOrphanedPin || Pair.Key->ParentPin || !Pair.Key->SubPins.IsEmpty() ||
            PinNumberKind(Pair.Key->PinType) < 0 || PinNumberKind(*Target) < 0)
        {
            Error = TEXT("Orphan/split/container numeric pin unsupported");
            return false;
        }
        auto NewType = *Target;
        NewType.bIsReference = Pair.Key->PinType.bIsReference;
        NewType.bIsConst = Pair.Key->PinType.bIsConst;
        S.Changes.Add(Pair.Value, NewType);
        if (Pair.Key->Direction == EGPD_Input && Pair.Key->LinkedTo.IsEmpty())
        {
            const FString Text = Pair.Key->DefaultValue.IsEmpty() ? TEXT("0"): Pair.Key->DefaultValue;
            TCHAR* End = nullptr;
            double Number = std::wcstod(*Text, &End);
            if (!End || !FString(End).TrimStartAndEnd().IsEmpty())
            {
                Error = TEXT("Invalid numeric pin literal");
                return false;
            }
            FDasScalarValue D, Original, Converted;
            D.Kind = 6;
            D.DoubleValue = Number;
            if (!ConvertDasNumber(D, PinNumberKind(Pair.Key->PinType), EDasIntegerRule::Exact,
                                  EDasFloatRule::RoundNearest, Original, Error) ||
                !ConvertDasNumber(Original, PinNumberKind(NewType), I, F, Converted, Error))
                return false;
            S.Defaults.Add(Pair.Value,
                           Converted.Kind == 0
                               ? FString::FromInt(Converted.IntValue)
                               : FString::Printf(TEXT("%.17g"), Converted.Kind == 1 ? double(Converted.FloatValue)
                                                                                    : Converted.DoubleValue));
            if (!Pair.Key->AutogeneratedDefaultValue.IsEmpty())
            {
                TCHAR* AutoEnd = nullptr;
                D.DoubleValue = std::wcstod(*Pair.Key->AutogeneratedDefaultValue, &AutoEnd);
                if (!AutoEnd || !FString(AutoEnd).TrimStartAndEnd().IsEmpty() ||
                    !ConvertDasNumber(D, PinNumberKind(Pair.Key->PinType), EDasIntegerRule::Exact,
                                      EDasFloatRule::RoundNearest, Original, Error) ||
                    !ConvertDasNumber(Original, PinNumberKind(NewType), I, F, Converted, Error))
                    return false;
                S.AutoDefaults.Add(Pair.Value, Converted.Kind == 0
                                                   ? FString::FromInt(Converted.IntValue)
                                                   : FString::Printf(TEXT("%.17g"), Converted.Kind == 1
                                                                                        ? double(Converted.FloatValue)
                                                                                        : Converted.DoubleValue));
            }
        }
    }
    for (const auto& Pin : ExplicitPins)
        if (!Indices.Contains(Pin.Key))
        {
            Error = TEXT("Explicit numeric pin outside snapshot scope");
            return false;
        }
    for (const auto& Pair : Indices)
        for (auto* Other : Pair.Key->LinkedTo)
        {
            auto* B = Indices.Find(Other);
            if (!B)
            {
                Error = TEXT("Graph link leaves supported scope");
                return false;
            }
            if (Pair.Value < *B)
                S.Edges.Add({Pair.Value, *B});
        }
    for (const auto& E : S.Edges)
        if (S.Changes.Contains(E.A) || S.Changes.Contains(E.B))
        {
            auto* A = S.Pin(E.A);
            auto* B = S.Pin(E.B);
            const int32 From = PinNumberKind(S.Type(A->Direction == EGPD_Output ? E.A : E.B)),
                        To = PinNumberKind(S.Type(A->Direction == EGPD_Input ? E.A : E.B));
            if (From < 0 || To < 0 || A->Direction == B->Direction ||
                (From != To && (S.Type(E.A).bIsReference || S.Type(E.B).bIsReference)))
            {
                Error = TEXT("Numeric link needs unsupported wildcard/container/reference conversion");
                return false;
            }
        }
    S.Handle = FCoreUObjectDelegates::OnObjectsReplaced.AddLambda(
        [&S](const FCoreUObjectDelegates::FReplacementObjectMap& Map)
        {
            for (auto& P : S.Pins)
            {
                if (auto* O = Map.Find(P.Type.PinSubCategoryObject.GetEvenIfUnreachable()))
                    P.Type.PinSubCategoryObject = *O;
                if (auto* O = Map.Find(P.Object.GetEvenIfUnreachable()))
                    P.Object = *O;
            }
        });
    return true;
}
bool FDasNumericGraphMigration::Apply(FString& Error)
{
    auto& S = *Impl;
    for (auto& G : S.Graphs)
        G.Graph->Modify();
    for (const auto& Change : S.Changes)
    {
        auto* P = S.Pin(Change.Key);
        if (!P)
        {
            Error = TEXT("Numeric graph pin disappeared");
            return false;
        }
        P->Modify();
        P->BreakAllPinLinks(false);
        P->PinType = Change.Value;
        if (auto* Default = S.Defaults.Find(Change.Key))
        {
            P->DefaultValue = *Default;
        }
        if (auto* AutoDefault = S.AutoDefaults.Find(Change.Key))
            P->AutogeneratedDefaultValue = *AutoDefault;
    }
    for (const auto& E : S.Edges)
        if (S.Changes.Contains(E.A) || S.Changes.Contains(E.B))
        {
            auto* A = S.Pin(E.A);
            auto* B = S.Pin(E.B);
            if (!A || !B)
            {
                Error = TEXT("Numeric link endpoint disappeared");
                return false;
            }
            auto* Output = A->Direction == EGPD_Output ? A : B;
            auto* Input = A->Direction == EGPD_Input ? A : B;
            const int32 From = PinNumberKind(Output->PinType), To = PinNumberKind(Input->PinType);
            Output->BreakLinkTo(Input);
            if (From == To)
            {
                Output->MakeLinkTo(Input);
                continue;
            }
            auto* Graph = Output->GetOwningNode()->GetGraph();
            auto* Adapter = NewObject<UK2Node_CallFunction>(Graph);
            Adapter->SetFromFunction(UDasNumericLibrary::StaticClass()->FindFunctionByName(CastName(From, To)));
            Graph->AddNode(Adapter);
            Adapter->CreateNewGuid();
            Adapter->PostPlacedNewNode();
            Adapter->AllocateDefaultPins();
            Adapter->NodePosX = (Output->GetOwningNode()->NodePosX + Input->GetOwningNode()->NodePosX) / 2;
            Adapter->NodePosY = Output->GetOwningNode()->NodePosY + 80;
            if (auto* Rule = Adapter->FindPin(TEXT("Rule")))
            {
                auto* Enum = StaticEnum<EDasIntegerRule>();
                FString Value = To == 0 ? Enum->GetNameStringByValue(int64(S.IntegerRule))
                                        : StaticEnum<EDasFloatRule>()->GetNameStringByValue(int64(S.FloatRule));
                Graph->GetSchema()->TrySetDefaultValue(*Rule, Value);
            }
            if (!Graph->GetSchema()->TryCreateConnection(Output, Adapter->FindPinChecked(TEXT("Value"))) ||
                                                         !Graph->GetSchema()->TryCreateConnection(
                                                             Adapter->GetReturnValuePin(), Input))
            {
                Error = TEXT("Cannot wire checked numeric adapter");
                return false;
            }
        }
    return true;
}
bool FDasNumericGraphMigration::Restore(FString& Error)
{
    auto& S = *Impl;
    bool OK = true;
    for (auto& G : S.Graphs)
    {
        auto Current = G.Graph->Nodes;
        for (auto& Entry : Current)
            if (auto* Node = Entry.Get();
                !G.Nodes.ContainsByPredicate([&](const auto& Original) { return Original.Get() == Node; }))
            {
                if (Node)
                {
                    Node->BreakAllNodeLinks();
                    G.Graph->RemoveNode(Node);
                }
            }
        for (auto& Node : G.Nodes)
            if (!G.Graph->Nodes.Contains(Node.Get()))
                G.Graph->AddNode(Node.Get());
    }
    for (int32 I = 0; I < S.Pins.Num(); ++I)
    {
        auto* P = S.Pin(I);
        if (!P)
        {
            OK = false;
            continue;
        }
        const auto& Old = S.Pins[I];
        P->BreakAllPinLinks(false);
        P->PinType = Old.Type;
        P->DefaultValue = Old.Default;
        P->AutogeneratedDefaultValue = Old.AutoDefault;
        P->DefaultTextValue = Old.Text;
        P->DefaultObject = Old.Object.Get();
        P->bOrphanedPin = Old.Orphaned;
    }
    for (const auto& E : S.Edges)
    {
        auto* A = S.Pin(E.A);
        auto* B = S.Pin(E.B);
        if (A && B)
            A->MakeLinkTo(B);
        else
            OK = false;
    }
    if (!OK)
        Error = TEXT("Cannot restore original graph pins/links");
    return OK;
}
